import type { SEl, StackSpec } from "./stack";

/* Level-stack and reflex-arc specs, one per pathway (the course's slide wording; labels are short names, the long text
 * lives in the tooltip and the popover). Keys: "n0".."n3" = the neuron's cell body (the node beat named after the neuron),
 * a stretch key of pathway-map.json = that tract, "~text" = a beat caption containing that text,
 * "start" / "startNerve" / "end" / "endNerve" = the receptor, the nerve in, the target, the nerve out. */

const n = (k: string | string[], at: string, lbl?: string, o: Partial<Extract<SEl, { t: "n" }>> = {}): SEl => ({ t: "n", k, at, lbl, ...o });
const p = (k: string | string[], pts: string[], lbl?: string, o: Partial<Extract<SEl, { t: "p" }>> = {}): SEl => ({ t: "p", k, pts, lbl, ...o });

/** the thalamus -> internal capsule -> cortex relay shared by the sensory pathways */
const relay = (nucleus: "vpl" | "vpm", target: "s1" | "fs", via: "corona" | "coronaF", lbl: string): SEl[] => [
  n("n2", `fb.${nucleus}:c`, lbl, { rx: 7, ry: 6 }),
  p("vpl-thal", [`fb.${nucleus}:c`, "fb.cap0:c"]),
  p("vpm-thal", [`fb.${nucleus}:c`, "fb.cap0:c"]),
  p("plic", ["fb.cap0:c", "fb.plic:c", `fb.${via}:c`], "Internal\ncapsule", { at: 1 }),
  p("s1", [`fb.${via}:c`, `fb.${target}:c`]),
  n("end", `fb.${target}:c`, target === "fs" ? "S1 (face)" : "S1 cortex", { rx: 8, ry: 5 }),
];

